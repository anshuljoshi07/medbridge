"""Embeds rules/*.json into lib/src/recon/rules_bundle.dart (generated).

    python3 tool/embed_rules.py          # regenerate
    python3 tool/embed_rules.py --check  # fail if stale (used by tool/check.sh)

The JSON files stay the human-edited source of truth (pharmacist rule guide);
the bundle lets the app, web dashboard and server load identical rules with
no file I/O, so device and server stamp the same ruleVersion.
"""
import json, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RULES = os.path.join(HERE, "..", "rules")
OUT = os.path.join(HERE, "..", "lib", "src", "recon", "rules_bundle.dart")

def render():
    parts = ["// GENERATED by tool/embed_rules.py from rules/*.json. Do not edit.\n",
             "// coverage:ignore-file\n\n",
             "/// Raw JSON of every shipped rule file, keyed by file stem.\n",
             "const Map<String, String> rulesBundleJson = {\n"]
    for name in sorted(os.listdir(RULES)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(RULES, name)) as fh:
            compact = json.dumps(json.load(fh), separators=(",", ":"), ensure_ascii=False)
        parts.append(f"  '{name[:-5]}': r'''{compact}''',\n")
    parts.append("};\n")
    return "".join(parts)

out = subprocess.run(
    ["dart", "format", "--output=show", "--stdin-name", OUT],
    input=render(), capture_output=True, text=True, check=True, cwd=os.path.join(HERE, ".."),
).stdout
if "--check" in sys.argv:
    if not os.path.exists(OUT) or open(OUT).read() != out:
        sys.exit("rules_bundle.dart is stale: run python3 tool/embed_rules.py")
    print("rules bundle fresh")
else:
    with open(OUT, "w") as fh:
        fh.write(out)
    print("wrote", OUT)
